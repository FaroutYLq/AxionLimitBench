"""Generate the compact Table 2 fragment from frozen ML4PS metrics.

Run in conda straxion. Does not edit the manuscript; table2.tex is the fragment
to insert. Confidence intervals resample papers 20,000 times with a fixed seed.
"""
import hashlib
import json
import math
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parent
REVISION = OUT.parents[1]
ARMS = ['agent_fable', 'agent_opus', 'agent_haiku',
        'pipeline_fable', 'pipeline_opus', 'pipeline_haiku']


def main():
    summary_path = REVISION/'ml4ps_coverage/summary.json'
    summary = json.loads(summary_path.read_text())
    report = {'coverage_summary_sha256': hashlib.sha256(summary_path.read_bytes()).hexdigest(),
              'bootstrap_resamples': 20000, 'bootstrap_seed': 20261103, 'arms': {}}
    for arm in ARMS:
        path = REVISION/'figures/figure4_residual_cdf_preview/data'/f'{arm}_metrics.json'
        metrics = json.loads(path.read_text())
        rows = [p for p in metrics['per_paper'] if p.get('comparison_status') == 'compared'
                and (p.get('interp_metrics') or {}).get('median_residual_dex') is not None
                and math.isfinite(p['interp_metrics']['median_residual_dex'])]
        values = np.array([p['interp_metrics']['median_residual_dex'] for p in rows])
        rng = np.random.default_rng(report['bootstrap_seed'])
        boot = values[rng.integers(0, len(values), (report['bootstrap_resamples'], len(values)))]
        lo, hi = np.percentile(np.median(boot, axis=1), [2.5, 97.5])
        assert len(rows) == summary[arm]['finite_cohort_n']
        report['arms'][arm] = {**summary[arm],
            'metrics_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
            'median_residual': float(np.median(values)), 'median_ci95': [float(lo), float(hi)],
            'macro_mean': metrics['per_type_aggregate']['macro_median_residual_dex'],
            'n_types': metrics['per_type_aggregate']['n_types'],
            'mean_pointwise_fraction': float(np.mean([p['interp_metrics']['frac_within_0_3dex'] for p in rows]))}
    data = [report['arms'][arm] for arm in ARMS]
    lines = [r'\begin{table}[tp]',
        r'% Generated by paper/revision/tables/table2_preview/make_table.py.',
        r'\caption{Comparison of three language models (Fable~5, Opus~4.8, and',
        r'Haiku~4.5), each using either an autonomous extraction agent or the fixed',
        r'multi-channel pipeline, on a common benchmark of 329 measured-limit papers.',
        r'A paper is \emph{compared} if its extraction yields a finite residual',
        r'against a curated reference in a compatible coupling plane.',
        r'Residual statistics use these $N$ comparisons; coverage and joint success',
        r'use the $N_{\rm curve}$ comparisons remaining after the exclusions described',
        r'in the text. Joint success requires both mass-range coverages $>90\%$ and',
        r'at least 90\% of compared points within 0.3~dex of the same reference.',
        r'Intervals are 95\% bootstrap confidence intervals over papers.}',
        r'\label{tab:results}', r'\centering', r'\begingroup',
        r'\fontsize{9}{10.8}\selectfont', r'\setlength{\tabcolsep}{2pt}',
        r'\renewcommand{\arraystretch}{1.16}',
        r'\begin{tabularx}{\textwidth}{@{}p{108pt}*{6}{>{\centering\arraybackslash}X}@{}}',
        r'\toprule',
        r' & \multicolumn{3}{c}{\textbf{Agent}} & \multicolumn{3}{c}{\textbf{Pipeline}} \\',
        r'\cmidrule(lr){2-4}\cmidrule(l){5-7}',
        r' & Fable 5 & Opus 4.8 & Haiku 4.5 & Fable 5 & Opus 4.8 & Haiku 4.5 \\',
        r'\midrule']
    def row(label, cells):
        lines.append(label + ' & ' + ' & '.join(cells) + r' \\')
    row(r'Finite comparisons, $N$', [str(d['finite_cohort_n']) for d in data])
    row('Median residual [dex]', [f"{d['median_residual']:.3f}" for d in data])
    row(r'95\% bootstrap CI', [r'{\fontsize{8}{9}\selectfont\mbox{'+f"{d['median_ci95'][0]:.3f}--{d['median_ci95'][1]:.3f}"+'}}' for d in data])
    row('Macro mean [dex]', [f"{d['macro_mean']:.3f}" for d in data])
    row(r'Mean pointwise agreement (\%)', [f"{100*d['mean_pointwise_fraction']:.1f}" for d in data])
    lines.append(r'\midrule')
    row(r'Curve subset, $N_{\rm curve}$', [str(d['coverage_denominator']) for d in data])
    row(r'$C_{\rm ref}>90\%$ (\%)', [f"{100*d['reference_gt90_fraction']:.1f}" for d in data])
    row(r'$C_{\rm ext}>90\%$ (\%)', [f"{100*d['extraction_gt90_fraction']:.1f}" for d in data])
    row(r'Both coverages $>90\%$ (\%)', [f"{100*d['both_gt90_fraction']:.1f}" for d in data])
    row(r'\textbf{Joint success (\%)}', [r'\textbf{'+f"{100*d['joint_success_fraction']:.1f}"+'}' for d in data])
    lines += [r'\bottomrule', r'\end{tabularx}', r'\endgroup', r'\end{table}']
    (OUT/'table2.tex').write_text('\n'.join(lines)+'\n')
    (OUT/'table2_data.json').write_text(json.dumps(report, indent=2)+'\n')
    print(OUT/'table2.tex')


if __name__ == '__main__':
    main()
